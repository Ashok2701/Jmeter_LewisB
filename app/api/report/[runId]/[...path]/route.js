import { requireAuth } from '@/lib/auth';
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { Readable } from 'node:stream';

import { OUTPUT_DIR } from '@/lib/config';
import { loadRun } from '@/lib/runs';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

const CONTENT_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.htm': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.map': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.eot': 'application/vnd.ms-fontobject',
  '.otf': 'font/otf',
  '.txt': 'text/plain; charset=utf-8',
  '.csv': 'text/csv; charset=utf-8',
};

/**
 * Serves the JMeter HTML dashboard generated by run_jmeter_test.bat.
 *
 * The dashboard lives in output\<timestamp>\dashboard\, outside webapp\public,
 * so it cannot be served statically. Its internal links are relative
 * ("content/js/...", "sbadmin2-1.0.7/..."), which resolve correctly against
 * /api/report/<runId>/index.html without any rewriting of the report.
 */
export async function GET(request, { params }) {
  const auth = await requireAuth(request);
  if (auth.response) return auth.response;

  const { runId, path: segments } = await params;

  const run = await loadRun(runId);
  if (!run || !run.outputFolderName) {
    return new Response('Report file is no longer available.', { status: 404 });
  }

  const dashboardDir = path.join(OUTPUT_DIR, run.outputFolderName, 'dashboard');

  // Path-traversal guard: the resolved target must stay inside dashboardDir.
  const requested = path.resolve(dashboardDir, ...(segments ?? ['index.html']));
  if (
    requested !== dashboardDir &&
    !requested.startsWith(dashboardDir + path.sep)
  ) {
    return new Response('Forbidden.', { status: 403 });
  }

  let stat;
  try {
    stat = await fsp.stat(requested);
  } catch {
    return new Response('Report file is no longer available.', { status: 404 });
  }
  if (stat.isDirectory()) {
    return new Response('Report file is no longer available.', { status: 404 });
  }

  const contentType =
    CONTENT_TYPES[path.extname(requested).toLowerCase()] ||
    'application/octet-stream';

  return new Response(Readable.toWeb(fs.createReadStream(requested)), {
    headers: {
      'Content-Type': contentType,
      'Content-Length': String(stat.size),
      'Cache-Control': 'no-store',
    },
  });
}
