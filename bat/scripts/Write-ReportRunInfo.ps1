<#
    Writes report-template\content\js\report-run-info.js for the run that has
    just finished, so the generated HTML dashboard's "Test Configuration" table
    describes that exact run.

    Called by run_jmeter_test.bat. Every value arrives through an environment
    variable rather than the command line, so nothing needs quoting and an
    Application Name containing & < > | " or spaces is handled safely.

    Expected environment variables:
        RUN_INFO_FILE       target .js file (required)
        APP_NAME            Application Name  (UI input)
        API_TYPE            API Type          (UI input)
        RUN_INFO_CSV        full path of the CSV this run used
        RUN_INFO_TOTAL_APIS API record count of that CSV
        RUN_INFO_THREADS    threads for this run
        RUN_INFO_RAMPUP     ramp-up seconds for this run
        RUN_INFO_LOOPS      loops for this run
        RUN_INFO_STARTED    display timestamp for this run
#>

$ErrorActionPreference = 'Stop'

$target = $env:RUN_INFO_FILE
if ([string]::IsNullOrWhiteSpace($target)) {
    Write-Error 'RUN_INFO_FILE is not set.'
    exit 1
}

function Get-IntOrZero($value) {
    $parsed = 0
    if ([int]::TryParse($value, [ref]$parsed)) { return $parsed }
    return 0
}

function Get-TextOrDefault($value, $fallback) {
    if ([string]::IsNullOrWhiteSpace($value)) { return $fallback }
    return $value.Trim()
}

# The CSV is reported by name only - the full path is a server-side detail and
# does not belong in a report handed to a client. CSV_DISPLAY_NAME is set by the
# web UI to the name of the file the client actually chose, since the file handed
# to JMeter is a normalised copy whose internal name would mean nothing to them.
$csvName = ''
if (-not [string]::IsNullOrWhiteSpace($env:CSV_DISPLAY_NAME)) {
    $csvName = Split-Path -Leaf $env:CSV_DISPLAY_NAME
} elseif (-not [string]::IsNullOrWhiteSpace($env:RUN_INFO_CSV)) {
    $csvName = Split-Path -Leaf $env:RUN_INFO_CSV
}

$info = [ordered]@{
    applicationName = Get-TextOrDefault $env:APP_NAME 'Not specified'
    apiType         = Get-TextOrDefault $env:API_TYPE 'Not specified'
    csvFile         = Get-TextOrDefault $csvName 'Not specified'
    totalApis       = Get-IntOrZero $env:RUN_INFO_TOTAL_APIS
    threads         = Get-IntOrZero $env:RUN_INFO_THREADS
    rampUpSeconds   = Get-IntOrZero $env:RUN_INFO_RAMPUP
    loops           = Get-IntOrZero $env:RUN_INFO_LOOPS
    testDateTime    = Get-TextOrDefault $env:RUN_INFO_STARTED (Get-Date -Format 'dd-MMM-yyyy hh:mm tt')
}

# ConvertTo-Json handles JavaScript-unsafe characters in the free-text fields.
$json = $info | ConvertTo-Json -Depth 3

$content = @"
/* Auto-generated by run_jmeter_test.bat before each report generation. Do not edit manually. */
var REPORT_RUN_INFO = $json;
"@

# UTF-8 without BOM - a BOM ahead of the script would be served as page content.
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($target, $content, $utf8NoBom)
